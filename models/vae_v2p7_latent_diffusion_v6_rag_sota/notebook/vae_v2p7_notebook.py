# --- 0. HYPERPARAMETER CONSTANTS ---
W_CONT      = 10.0
W_BOOL      = 5.0
W_CAT       = 15.0
W_MOD_GATE  = 5.0

# ==============================================================================
# 1. SHARED LAYERS
