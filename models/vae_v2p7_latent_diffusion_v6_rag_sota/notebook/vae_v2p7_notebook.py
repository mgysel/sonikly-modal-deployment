def interpolate_prompts(model, start_prompt, end_prompt, steps=10, z_seed=42):
    """
    Morphs between two text descriptions using the VAE Decoder.
    Note: This bypasses the Diffusion Denoiser to show the VAE's smooth latent manifold.
    """
    # 1. Encode both prompts
    emb_start = clap_encode_text([start_prompt])[0]
    emb_end = clap_encode_text([end_prompt])[0]

    # 2. Fixed Z (use mean 0 for "standard" representation)
    np.random.seed(z_seed)
    z_fixed = np.random.normal(size=(1, int(model.vae_encoder.output_shape[0][1]))).astype('float32')

    # 3. Linear Interpolation
    interpolated_params = []
    alphas = np.linspace(0, 1, steps)

    print(f"Morphing: '{start_prompt}' -> '{end_prompt}'")

    for alpha in alphas:
        # Interpolate text embedding
        emb_interp = (1 - alpha) * emb_start + alpha * emb_end
        emb_interp = emb_interp.reshape(1, -1)

        # !!! FIXED: Use .vae_decoder
        preds = model.vae_decoder.predict([z_fixed, emb_interp], verbose=0)

        # Reconstruct
        param_map = {int(p['id']): p for g in SERUM_PARAMETERS.values() for p in g}
        params = reconstruct_parameters_from_heads(
            preds,
            parameter_types=param_map,
            categorical_num_classes=categorical_num_classes,
            sample_categorical=False, # Deterministic for smooth plots
            noise_level=0.0
        )
        interpolated_params.append(params)

    return np.array(interpolated_params), alphas

