def _safe_probs(raw_head):
    probs = np.array(raw_head, dtype=np.float32).reshape(-1)
    probs[probs < 0] = 0.0
    s = probs.sum()
    if not np.isfinite(s) or s <= 1e-6:
        probs = np.ones_like(probs, dtype=np.float32) / probs.size
    else:
        probs = probs / s
    return probs

def reconstruct_parameters_from_heads(predicted_outputs, parameter_types, categorical_num_classes, sample_categorical=True, noise_level=0.0):
    """
    Reconstructs parameter vector from split heads.
    """
    n_params = len(parameter_types)
    reconstructed = np.zeros(n_params, dtype=np.float32)

    continuous_params = [int(i) for i, p in parameter_types.items() if p["type"] == "continuous"]
    mod_matrix_ids = set(range(170, 202))

    unipolar_indices = sorted([i for i in continuous_params if i not in mod_matrix_ids])
    bipolar_indices = sorted([i for i in continuous_params if i in mod_matrix_ids])
    boolean_params = sorted([int(i) for i, p in parameter_types.items() if p["type"] == "boolean"])
    categorical_params = sorted([int(i) for i, p in parameter_types.items() if p["type"] == "categorical"])

    head_idx = 0

    if unipolar_indices:
        uni_head = np.array(predicted_outputs[head_idx], dtype=np.float32).reshape(-1)
        for i, param_idx in enumerate(unipolar_indices):
            reconstructed[param_idx] = uni_head[i]
        head_idx += 1

    if bipolar_indices:
        gate_head = np.array(predicted_outputs[head_idx], dtype=np.float32).reshape(-1)
        val_head = np.array(predicted_outputs[head_idx+1], dtype=np.float32).reshape(-1)
        head_idx += 2
        for i, param_idx in enumerate(bipolar_indices):
            gate = 1.0 / (1.0 + np.exp(-gate_head[i]))
            val = (val_head[i] + 1.0) / 2.0
            if gate < 0.25: reconstructed[param_idx] = 0.5
            else: reconstructed[param_idx] = val

    if boolean_params:
        bool_head = np.array(predicted_outputs[head_idx], dtype=np.float32).reshape(-1)
        head_idx += 1
        for i, param_idx in enumerate(boolean_params):
            reconstructed[param_idx] = 1.0 if bool_head[i] > 0.5 else 0.0

    for param_idx in categorical_params:
        head = predicted_outputs[head_idx]
        if isinstance(head, (list, tuple)): head = head[0]
        probs = _safe_probs(head)
        num_c = categorical_num_classes[param_idx]
        if sample_categorical: choice = np.random.choice(len(probs), p=probs)
        else: choice = np.argmax(probs)
        if num_c > 1: reconstructed[param_idx] = float(choice) / (num_c - 1)
        else: reconstructed[param_idx] = 0.0
        head_idx += 1

    return reconstructed

def retrieve_closest_preset(target_emb, db_embeddings, db_params):
    """
    Finds the single closest preset in the training set using Cosine Similarity.
    """
    # Dot product (since embeddings are normalized)
    scores = np.dot(db_embeddings, target_emb.T).flatten()
    best_idx = np.argmax(scores)
    print(f"🔎 RAG Retrieval: Found match at index {best_idx} (Score: {scores[best_idx]:.4f})")

    # Return the parameters of that preset
    return db_params[best_idx:best_idx+1]

def generate_synth_parameters_vae(text_description, model, parameter_types, categorical_num_classes,
                                  sample_categorical=True, noise_level=0.0, seed=None,
                                  guidance_scale=7.5, use_rag=True, rag_strength=0.8):
    if seed is not None:
        import torch
        np.random.seed(seed)
        random.seed(seed)
        tf.random.set_seed(seed)
        torch.manual_seed(seed)

    # 1. Encode Text
    emb = clap_encode_text([text_description])

    # 2. RAG Logic (Retrieve & Encode)
    initial_latent = None
    if use_rag:
        # We access the global training data from Cell 2.1/3.1
        # X_train (Embeds) and y_train (Params)
        if 'X_train' in globals() and 'y_train' in globals():
            # Get closest params
            retrieved_params = retrieve_closest_preset(emb, globals()['X_train'], globals()['y_train'])

            # Encode them into latent space using the model's VAE Encoder
            # (Note: We pass the target text embedding, not the retrieved text embedding, for conditioning)
            z_mean, z_log_var = model.vae_encoder([emb, retrieved_params], training=False)
            initial_latent = z_mean # Use mean for stability
        else:
            print("⚠️ Warning: Training data not found in globals. Skipping RAG.")

    # 3. Generate
    print(f"Diffusion Sampling for: '{text_description}' (CFG: {guidance_scale}, RAG: {use_rag})...")

    preds = model.generate(emb, steps=1000, guidance_scale=guidance_scale,
                           initial_latent=initial_latent, strength=rag_strength)

    # 4. Reconstruct
    return reconstruct_parameters_from_heads(preds, parameter_types, categorical_num_classes, sample_categorical=sample_categorical, noise_level=noise_level)

def numpy_to_json(parameter_array, serum_parameters):
    output_json = {}
    flat_lookup = {}
    for group, params in serum_parameters.items():
        for p in params:
            flat_lookup[int(p["id"])] = p

    for idx, val in enumerate(parameter_array):
        if idx in flat_lookup:
            param_def = flat_lookup[idx]
            entry = param_def.copy()
            entry["value"] = float(val)
            output_json[str(idx)] = entry

    return output_json

