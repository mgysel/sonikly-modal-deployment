# --- CYCLICAL BETA CALLBACK ---
class CyclicalBetaAnnealing(tf.keras.callbacks.Callback):
    def __init__(self, cycle_epochs=20, max_beta=0.01):
        super().__init__()
        self.cycle_epochs = cycle_epochs
        self.max_beta = max_beta

    def on_epoch_begin(self, epoch, logs=None):
        cycle_pos = (epoch % self.cycle_epochs) / self.cycle_epochs
        if cycle_pos < 0.5:
            current_beta = self.max_beta * (cycle_pos * 2)
        else:
            current_beta = self.max_beta
        if hasattr(self.model, "beta"):
            self.model.beta.assign(float(current_beta))

# --- EMA CALLBACK (FIXED) ---
class EMACallback(tf.keras.callbacks.Callback):
    """ Applies Exponential Moving Average to model weights during training """
    def __init__(self, source_model, ema_model, decay=0.999):
        super().__init__()
        self.source_model = source_model  # <--- RENAMED to avoid conflict with self.model
        self.ema_model = ema_model
        self.decay = decay

    def on_train_batch_end(self, batch, logs=None):
        # Update EMA weights: new_ema = decay * old_ema + (1 - decay) * new_weights
        for weight, ema_weight in zip(self.source_model.trainable_variables, self.ema_model.trainable_variables):
            ema_weight.assign(self.decay * ema_weight + (1 - self.decay) * weight)

